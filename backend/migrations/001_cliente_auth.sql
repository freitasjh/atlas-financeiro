-- AUTH-09 / RF-07 — versão 1 do schema cliente em CLIENTE_DB.
-- Aditiva e idempotente; 0 segredo, 0 URL, 0 dado de tenant, 0 PSP.
BEGIN;

CREATE SCHEMA IF NOT EXISTS cliente;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'cliente_app_role') THEN
    CREATE ROLE cliente_app_role NOLOGIN;
  END IF;
END
$$;

REVOKE ALL ON SCHEMA cliente FROM PUBLIC;
GRANT USAGE ON SCHEMA cliente TO cliente_app_role;

CREATE TABLE IF NOT EXISTS cliente.credenciais (
  sub text PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role text NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente.refresh_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sub text NOT NULL,
  token_hash text NOT NULL UNIQUE,
  family_id text NOT NULL,
  jti text NOT NULL,
  estado text NOT NULL CHECK (estado IN ('ativo', 'usado', 'revogado')),
  expira_em timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente.revogacoes (
  jti text PRIMARY KEY,
  sub text NOT NULL,
  motivo text NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS cliente.mfa (
  sub text PRIMARY KEY,
  enrolled boolean NOT NULL DEFAULT false
);

-- FORCE cobre também o dono da tabela; superusuario continua fora (BYPASSRLS).
ALTER TABLE cliente.credenciais ENABLE ROW LEVEL SECURITY;
ALTER TABLE cliente.refresh_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE cliente.revogacoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE cliente.mfa ENABLE ROW LEVEL SECURITY;
ALTER TABLE cliente.credenciais FORCE ROW LEVEL SECURITY;
ALTER TABLE cliente.refresh_tokens FORCE ROW LEVEL SECURITY;
ALTER TABLE cliente.revogacoes FORCE ROW LEVEL SECURITY;
ALTER TABLE cliente.mfa FORCE ROW LEVEL SECURITY;

-- Uma policy por tabela: só linhas do sub da sessão; sem sub, default-deny.
DROP POLICY IF EXISTS credenciais_own ON cliente.credenciais;
CREATE POLICY credenciais_own ON cliente.credenciais
  FOR ALL TO cliente_app_role
  USING (sub = current_setting('app.cliente_sub', true))
  WITH CHECK (sub = current_setting('app.cliente_sub', true));

DROP POLICY IF EXISTS refresh_tokens_own ON cliente.refresh_tokens;
CREATE POLICY refresh_tokens_own ON cliente.refresh_tokens
  FOR ALL TO cliente_app_role
  USING (sub = current_setting('app.cliente_sub', true))
  WITH CHECK (sub = current_setting('app.cliente_sub', true));

DROP POLICY IF EXISTS revogacoes_own ON cliente.revogacoes;
CREATE POLICY revogacoes_own ON cliente.revogacoes
  FOR ALL TO cliente_app_role
  USING (sub = current_setting('app.cliente_sub', true))
  WITH CHECK (sub = current_setting('app.cliente_sub', true));

DROP POLICY IF EXISTS mfa_own ON cliente.mfa;
CREATE POLICY mfa_own ON cliente.mfa
  FOR ALL TO cliente_app_role
  USING (sub = current_setting('app.cliente_sub', true))
  WITH CHECK (sub = current_setting('app.cliente_sub', true));

GRANT SELECT, INSERT, UPDATE, DELETE ON
  cliente.credenciais,
  cliente.refresh_tokens,
  cliente.revogacoes,
  cliente.mfa
TO cliente_app_role;

-- AUTH-07: único acesso sem `sub` conhecido — resolver hash→sub para iniciar a
-- rotação. SECURITY DEFINER é estreito (só esta coluna); toda outra leitura/escrita
-- do app roda sob cliente_app_role com policy de linha ativa.
CREATE OR REPLACE FUNCTION cliente.sub_por_hash_refresh(p_token_hash text)
RETURNS text
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = cliente, pg_temp
AS $$
  SELECT sub FROM cliente.refresh_tokens WHERE token_hash = p_token_hash
$$;
REVOKE ALL ON FUNCTION cliente.sub_por_hash_refresh(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cliente.sub_por_hash_refresh(text) TO cliente_app_role;

-- AUTH-05: resolução email→sub. Função PRÓPRIA e estreita: uma coluna (sub),
-- search_path fixo, EXECUTE só para cliente_app_role. Não estende nem reusa a de
-- hash-refresh, que continua limitada a refresh_tokens.
CREATE OR REPLACE FUNCTION cliente.sub_por_email(p_email text)
RETURNS text
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = cliente, pg_temp
AS $$
  SELECT sub FROM cliente.credenciais WHERE email = p_email
$$;
REVOKE ALL ON FUNCTION cliente.sub_por_email(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cliente.sub_por_email(text) TO cliente_app_role;

COMMIT;
